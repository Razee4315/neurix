export function isKnownIcon(name: string): boolean {
	return ICONS.has(name);
}

/** At and below this size the theme's sturdier weight is used. */
const SMALL = 16;

interface IconProps {
	name: string;
	size?: number;
	/** Draw the solid version, for selected / emphasised states. */
	fill?: boolean;
	color?: string;
	className?: string;
}

export function Icon({ name, size = 24, fill = false, color, className }: IconProps) {
	const weights = useIconWeights();
	const Glyph = ICONS.get(name) ?? Sparkle;
	const weight = fill ? "fill" : size <= SMALL ? weights.small : weights.regular;
	return (
		<Glyph
			className={className}
			size={size}
			color={color ?? "currentColor"}
			weight={weight}
			style={{ flexShrink: 0 }}
			{...DECORATIVE}
		/>
	);
}
