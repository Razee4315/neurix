/**
 * Icons are looked up by name. The names are the ones stored with user data
 * (a character's icon), so they stay stable even though the artwork behind
 * them has changed over time. Unknown names fall back to a neutral glyph.
 *
 * The artwork is Phosphor. Each icon comes in several weights, and the
 * active theme chooses which one is drawn (see theme/themes.ts): two-tone
 * for Obsidian, fine line for Paper, heavy for Phosphor, filled for Dusk.
 */
interface GlyphProps {
	size?: number | string;
	color?: string;
	weight?: IconWeight;
	className?: string;
	style?: CSSProperties;
}

